// GetRandomDare selects a cryptographically safe random dare from the catalog.
func GetRandomDare() models.Dare {
	n := big.NewInt(int64(len(AllDares)))
	idx, err := rand.Int(rand.Reader, n)
	if err != nil {
		return AllDares[0]
	}
	return AllDares[idx.Int64()]
}

// FindDareByID locates a dare by its unique slug ID.
func FindDareByID(id string) (models.Dare, bool) {
	for _, d := range AllDares {
		if strings.EqualFold(d.ID, id) {
			return d, true
		}
	}
	return models.Dare{}, false
}
